export const cleanCrosswordWord=(word,lang)=>String(word).toLocaleUpperCase(lang).normalize('NFD').replace(/[\u0300-\u036f\u064b-\u065f\u0670]/g,'').replace(/\s/g,'').replace(/[^\p{L}]/gu,'');
export function buildCrossword(lang,puzzleIndex=0){
 const packs=crosswordPacks[lang];if(!packs)throw Error('Unsupported crossword language');
 const index=((Number(puzzleIndex)||0)%packs.length+packs.length)%packs.length;
 const bank=packs[index].map(([word,clue])=>({word:cleanCrosswordWord(word,lang),clue})).filter(x=>x.word.length>=3);
 const N=19,b=Array.from({length:N},()=>Array(N).fill('')),axes=Array.from({length:N},()=>Array.from({length:N},()=>new Set()));
 const across=lang==='ar'?{dr:0,dc:-1}:{dr:0,dc:1},down={dr:1,dc:0};
 const placed=[],orientation=(w,axis)=>axis==='across'?across:down;
 const within=(r,c)=>r>=0&&r<N&&c>=0&&c<N;
 function check(word,r,c,axis,first=false){
  const {dr,dc}=orientation(word,axis),lastR=r+dr*(word.length-1),lastC=c+dc*(word.length-1);
  if(!within(r,c)||!within(lastR,lastC)||within(r-dr,c-dc)&&b[r-dr][c-dc]||within(lastR+dr,lastC+dc)&&b[lastR+dr][lastC+dc])return null;
  let intersects=0;
  for(let i=0;i<word.length;i++){
   const rr=r+i*dr,cc=c+i*dc,existing=b[rr][cc];
   if(existing){
    if(existing!==word[i]||axes[rr][cc].has(axis))return null;
    intersects++;
   }else{
    for(const dir of axis==='across'?[[1,0],[-1,0]]:[[0,1],[0,-1]]){
      const nr=rr+dir[0],nc=cc+dir[1];if(within(nr,nc)&&b[nr][nc])return null;
    }
   }
  }
  if(!first&&intersects===0)return null;
  return {r,c,axis,intersects,score:intersects*90-Math.abs(r-9)-Math.abs(c-9)-word.length/10};
 }
 function add(w,position){
  const {dr,dc}=orientation(w.word,position.axis),cells=[];
  for(let i=0;i<w.word.length;i++){
   const r=position.r+dr*i,c=position.c+dc*i;
   b[r][c]=w.word[i];axes[r][c].add(position.axis);cells.push([r,c]);
  }
  placed.push({answer:w.word,clue:w.clue,axis:position.axis,cells});
 }
 let [first,...others]=bank.sort((a,b)=>b.word.length-a.word.length);
 const startAxis='across',startCol=lang==='ar'?Math.ceil((N+first.word.length-1)/2):Math.floor((N-first.word.length)/2);
 add(first,check(first.word,Math.floor(N/2),startCol,startAxis,true));
 let todo=others;
 for(let pass=0;pass<3;pass++){
  const left=[];
  for(const w of todo){
   const options=[];
   for(const axis of ['across','down']){
    const {dr,dc}=orientation(w.word,axis);
    for(let i=0;i<w.word.length;i++){
     for(let r=0;r<N;r++)for(let c=0;c<N;c++)if(b[r][c]===w.word[i]){
      const q=check(w.word,r-dr*i,c-dc*i,axis);
      if(q)options.push(q);
     }
    }
   }
   options.sort((a,b)=>b.score-a.score||a.r-b.r||a.c-b.c);
   if(options.length&&placed.length<14)add(w,options[0]);else left.push(w);
  }
  todo=left;
 }
 if(placed.length<7)throw Error('Crossword has too few intersecting words: '+lang+'/'+index+'/'+placed.length);
 const rmin=Math.min(...placed.flatMap(e=>e.cells.map(c=>c[0]))),cmin=Math.min(...placed.flatMap(e=>e.cells.map(c=>c[1])));
 const rmax=Math.max(...placed.flatMap(e=>e.cells.map(c=>c[0]))),cmax=Math.max(...placed.flatMap(e=>e.cells.map(c=>c[1])));
 const height=rmax-rmin+1,width=cmax-cmin+1;
 const cells=Array.from({length:height},(_,r)=>Array.from({length:width},(_,c)=>b[r+rmin][c+cmin]||null));
 placed.forEach(e=>e.cells=e.cells.map(([r,c])=>[r-rmin,c-cmin]));
 const startCells=new Map;
 placed.forEach(e=>{const [r,c]=e.cells[0];startCells.set(r+','+c,0)});
 let count=0;const numbered=[...startCells.keys()].sort((a,b)=>{const [ra,ca]=a.split(',').map(Number),[rb,cb]=b.split(',').map(Number);return ra-rb||ca-cb;});
 for(const k of numbered)startCells.set(k,++count);
 placed.forEach(e=>{const [r,c]=e.cells[0];e.number=startCells.get(r+','+c);});
 placed.sort((a,b)=>a.number-b.number||(a.axis==='across'?-1:1));
 const intersections=new Set;
 for(const e of placed)for(const [r,c] of e.cells){
  const all=placed.filter(w=>w.cells.some(([wr,wc])=>wr===r&&wc===c));
  if(all.length>1)intersections.add(r+','+c);
 }
 if(intersections.size<placed.length-1)throw Error('Crossword lacks true letter intersections');
 return {lang,index,cells,height,width,entries:placed,intersectionCount:intersections.size};
}
